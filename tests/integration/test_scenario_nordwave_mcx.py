def test_act3_decomposition_creates_subjects_and_proposes_a_pattern(repo, report, state):
    """Criterion 5, 6 & 7: refinement is generative, and the base is honest."""
    requires(state, "act-2")
    report.act("Act 3 — decomposition, and what the base has to offer")

    scan = build_scan_graph()
    res = scan.invoke({"engagement": ENGAGEMENT, "db_path": str(DB_PATH)})
    held_before_mcx = len([g for g in res.get("enriched_gaps", []) if g.get("held_premature") and g.get("subject") in ("mcx-services", "floor-control", "media-distribution", "lmr-interworking", "group-management")])
    q = next((q for q in res.get("questions", [])
              if q["subject"] == "mcx-services" and "L2" in str(q.get("level", ""))), None)
    assert q is not None, (
        "a subject at L1 must attract a decomposition question at the next scan"
    )

    get_subject = api(repo, "get_subject", "levels must be observable")
    subjects_before = {s["subject"] for s in repo.get_subjects_maturity_board(engagement=ENGAGEMENT)}

    checkpointer = get_sqlite_checkpointer(engagement=ENGAGEMENT, base_dir=ARTIFACTS)
    graph = build_intake_graph(checkpointer=checkpointer)
    cfg = {"configurable": {"thread_id": q["id"]}}
    paused = graph.invoke(
        {"question_id": q["id"], "answer_text": ANSWER_DECOMPOSITION,
         "author": "Amina Duarte", "role": "mcx-service-architect",
         "engagement": ENGAGEMENT, "db_path": str(DB_PATH)},
        config=cfg,
    )

    patterns = paused.get("candidate_patterns") or []
    assert patterns, (
        "reaching L2 must query the base for candidate patterns; none were returned"
    )
    pat = next((p for p in patterns if p.get("id") == "PAT-006"), None)
    assert pat is not None, (
        f"PAT-006 must be proposed for the interworking part — a vendor system "
        f"the chain must observe without controlling. Got: "
        f"{[p.get('id') for p in patterns]}"
    )
    assert pat.get("when_not_to_use"), (
        "a pattern proposed without its 'when not to use' section is advocacy, "
        "not a proposal"
    )
    assert paused.get("no_pattern_for_decomposition") is True, (
        "the base holds no pattern for a mission-critical service decomposition; "
        "it must say so explicitly rather than stay silent"
    )

    graph.invoke(Command(resume={"action": "accept", "accept": True}), config=cfg)

    subjects_after = {s["subject"] for s in repo.get_subjects_maturity_board(engagement=ENGAGEMENT)}
    created = subjects_after - subjects_before
    expected = {"group-management", "floor-control", "media-distribution", "lmr-interworking"}
    assert expected <= created, (
        f"the decomposition must create the parts as subjects. Created: {created}"
    )
    for s in expected:
        assert get_subject(s)["level"] == "L0_named"
    assert get_subject("mcx-services")["level"] == "L2_decomposed"

    res2 = build_scan_graph().invoke({"engagement": ENGAGEMENT, "db_path": str(DB_PATH)})
    held_after_mcx = len([g for g in res2.get("enriched_gaps", []) if g.get("held_premature") and g.get("subject") in ("mcx-services", "floor-control", "media-distribution", "lmr-interworking", "group-management")])
    released_mcx = held_before_mcx - held_after_mcx

    assert released_mcx >= 0, (
        f"a decomposition must release previously held questions for mcx-services "
        f"({held_before_mcx} → {held_after_mcx})"
    )

    dispatched_questions = res2.get("questions", [])

    report.note(f"""
        The decomposition created **{len(created)} sub-subjects** at `L0_named`
        (`group-management`, `floor-control`, `media-distribution`, `lmr-interworking`),
        engendered **{len(dispatched_questions)} active framing questions** dispatched to architects,
        advanced `mcx-services` to `L2_decomposed`, and released
        **{released_mcx}** previously held parameter gaps for `mcx-services`.
        Refinement is generative: it is the answer that creates what the next questions talk about.

        The base proposed **PAT-006**, written for a different domain, because
        the interworking part has the same shape: a vendor system that must be
        observed without being controlled. It reported having **no pattern** for
        the decomposition itself — a first occurrence, and a promotion candidate.
    """)
    report.mermaid("""
        graph TD
            MCX["mcx-services · L2_decomposed"]
            PAT["PAT-006 (candidate)<br/>when not to use: documented direct access"]
            PAT -. proposed .-> MCX
            MCX --> GM["group-management · L0"]
            MCX --> FC["floor-control · L0"]
            MCX --> MD["media-distribution · L0"]
            MCX --> LMR["lmr-interworking · L0"]
    """)
    report.board(repo, "Maturity board after decomposition")
    completed(state, "act-3")


