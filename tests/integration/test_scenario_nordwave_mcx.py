# ---------------------------------------------------------------- utilities
def api(obj, name: str, criterion: str):
    """Fetch a required method, failing with what is missing and why."""
    fn = getattr(obj, name, None)
    if fn is None:
        pytest.fail(
            f"NOT IMPLEMENTED: {type(obj).__name__}.{name}() is required by "
            f"acceptance criterion: {criterion}"
        )
    return fn


class Report:
    """Accumulates the progression report. Every figure is derived from the graph."""

    def __init__(self, path: Path):
        self.path = path
        self.parts: list[str] = [
            f"# Progression report — {ENGAGEMENT}\n",
            "_Generated by the acceptance test, from the engagement graph. "
            "Every board and every diagram below is a projection of the database "
            "at that point in the run; none of it is written by hand._\n",
        ]
        self.acts_completed: set[str] = set()

    def act(self, title: str) -> None:
        self.parts.append(f"\n---\n\n## {title}\n")

    def note(self, text: str) -> None:
        self.parts.append(textwrap.dedent(text).strip() + "\n")

    def table(self, headers: list[str], rows: list[list[str]]) -> None:
        self.parts.append("| " + " | ".join(headers) + " |")
        self.parts.append("|" + "|".join(["---"] * len(headers)) + "|")
        for r in rows:
            self.parts.append("| " + " | ".join(str(c) for c in r) + " |")
        self.parts.append("")

    def mermaid(self, body: str) -> None:
        self.parts.append("```mermaid\n" + textwrap.dedent(body).strip() + "\n```\n")

    def board(self, repo, caption: str) -> None:
        """Renders the maturity board straight from the repository."""
        rows = api(repo, "get_subjects_maturity_board",
                   "the maturity board is the overview of what is left to instruct")(
            engagement=ENGAGEMENT)
        levels = ["L0_named", "L1_framed", "L2_decomposed", "L3_decided", "L4_specified"]
        out = []
        for row in rows:
            reached = levels.index(row.get("level", "L0_named"))
            cells = ["█" if i <= reached else "·" for i in range(len(levels))]
            out.append([row["subject"], " ".join(cells), row.get("level", ""),
                        row.get("blocked_by", "—")])
        self.note(f"**{caption}**")
        self.table(["Subject", "L0 L1 L2 L3 L4", "Level", "Blocked by"], out)

    def write(self) -> None:
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text("\n".join(self.parts), encoding="utf-8")


