def requires(state: dict, act: str):
    if act not in state.get("done", set()):
        pytest.skip(f"depends on {act}, which did not complete")


def completed(state: dict, act: str):
    state.setdefault("done", set()).add(act)


# ============================================================== ACT 1
def test_act1_first_scan_gates_premature_questions(repo, report, state):
    """Criterion 1 & 2: few questions dispatched, many held, reasons visible."""
    report.act("Act 1 — first scan on an empty graph")

    scan = build_scan_graph()
    res = scan.invoke({"engagement": ENGAGEMENT, "db_path": str(DB_PATH)})

    questions = res.get("questions", [])
    gaps = res.get("enriched_gaps", [])
    held = [g for g in gaps if g.get("held_premature")]

    # The discriminating assertions. A run that dispatches everything has not
    # tested the gate; a run that dispatches one question has not tested it either.
    assert len(questions) >= 2, "the first scan must open several framing questions"
    assert len(held) >= 5, (
        f"only {len(held)} gaps held: the level gate is not doing its job. "
        f"On an empty graph most gaps must be premature."
    )
    for g in held:
        assert g.get("held_reason"), (
            "every held gap must carry a readable reason; a silent suppression "
            "is indistinguishable from a missing rule"
        )

    # No dispatched question may be above the maturity of its subject.
    get_subject = api(repo, "get_subject", "questions must match the subject level")
    for q in questions:
        subj = get_subject(q["subject"])
        assert q.get("level") in (None, "L1_framing") or subj["level"] != "L0_named", (
            f"{q['id']} asks a {q.get('level')} question of a subject at "
            f"{subj['level']}"
        )

    report.note(f"""
        Gaps found: **{len(gaps)}** · dispatched: **{len(questions)}** ·
        held by the level gate: **{len(held)}**.

        The ratio is what matters, not the values. Suppression reasons are
        carried on every held gap; a sample follows.
    """)
    report.table(["Held gap", "Reason"],
                 [[g.get("gap_type", "?"), g["held_reason"]] for g in held[:5]])
    report.table(["Question", "Subject", "Routed to", "Blocks"],
                 [[q["id"], q["subject"], q.get("routed_to", "?"),
                   ", ".join(q.get("blocking", []))] for q in questions])
    report.mermaid("""
        graph TD
            GATE["Level gate: %d gaps held"]:::held
            %s
            classDef held stroke-dasharray: 4 3;
    """ % (len(held),
           "\n            ".join(
               f'{q["id"].replace("-", "")}["{q["id"]} → {q["subject"]}"]'
               for q in questions)))

    state["questions_act1"] = questions
    state["held_count_act1"] = len(held)
    completed(state, "act-1")


# ============================================================== ACT 2
def test_act2_extraction_differentiates_confidence(repo, report, state):
    """Criterion 3 & 4: the extraction, not the test, produces the statements."""
    requires(state, "act-1")
    report.act("Act 2 — framing, and what the extraction makes of a nuanced answer")

    q = next(q for q in state["questions_act1"] if q["subject"] == "mcx-services")
    get_subject = api(repo, "get_subject", "level advancement must be observable")
    before = get_subject("mcx-services")["level"]

    checkpointer = get_sqlite_checkpointer(engagement=ENGAGEMENT, base_dir=ARTIFACTS)
    graph = build_intake_graph(checkpointer=checkpointer)
    cfg = {"configurable": {"thread_id": q["id"]}}

    paused = graph.invoke(
        {"question_id": q["id"], "answer_text": ANSWER_FRAMING,
         "author": "Amina Duarte", "role": "mcx-service-architect",
         "engagement": ENGAGEMENT, "db_path": str(DB_PATH)},
        config=cfg,
    )
    proposed = paused.get("proposed_statements") or paused.get("__interrupt__", [{}])[0]
    assert proposed, "the flow must pause with a proposal before recording anything"

    # Nothing may exist yet.
    assert not repo.get_active_statements(engagement=ENGAGEMENT), (
        "statements were persisted before confirmation"
    )

    result = graph.invoke(Command(resume={"action": "accept", "accept": True}), config=cfg)
    ids = result.get("persisted_statement_ids", [])
    assert len(ids) >= 2, "a four-clause answer must yield more than one statement"

    get_statement = api(repo, "get_statement", "confidence must be inspectable per statement")
    stmts = [get_statement(i) for i in ids]
    confidences = {s["confidence"] for s in stmts}
    assert len(confidences) >= 2, (
        f"extraction flattened confidence to {confidences}: the answer contains "
        f"both a design decision and a customer requirement, and they cannot "
        f"carry the same epistemic status"
    )

    verbatim = {s.get("verbatim", "") for s in stmts}
    assert any(ANSWER_FRAMING[:60] in v for v in verbatim), (
        "the contributor's own words must be preserved with the statements"
    )

    get_unc = api(repo, "get_uncertainties",
                  "an admitted unknown must be recorded as such, not as a fact")
    uncertainties = get_unc(engagement=ENGAGEMENT, subject="mcx-services")
    assert uncertainties, (
        "the answer ends on 'I do not yet know whether...' — that must be an "
        "uncertainty, not a statement and not silence"
    )
    for s in stmts:
        assert "do not yet know" not in s["value"].lower(), (
            "an admitted unknown was promoted to a statement"
        )

    after = get_subject("mcx-services")["level"]
    assert before == "L0_named" and after == "L1_framed", (
        f"level must advance through the flow, not through a test call "
        f"({before} → {after})"
    )

    report.note(f"""
        Amina's answer produced **{len(ids)} statements** with
        **{len(confidences)} distinct confidence levels**, one uncertainty, and
        advanced `mcx-services` from `{before}` to `{after}`.
    """)
    report.table(["Id", "Predicate", "Value", "Confidence"],
                 [[s["id"], s["predicate"], s["value"], s["confidence"]] for s in stmts])
    report.table(["Recorded uncertainty"], [[u["text"]] for u in uncertainties])

    state["framing_ids"] = ids
    completed(state, "act-2")


# ============================================================== ACT 2b
def test_act2b_interrupt_resumes_in_a_separate_process(repo, report, state):
    """The load-bearing durability test: a resume days later, from another process."""
    requires(state, "act-2")
    report.act("Act 2b — resuming an interrupted conversation from another process")

    scan = build_scan_graph()
    res = scan.invoke({"engagement": ENGAGEMENT, "db_path": str(DB_PATH)})
    q = next((q for q in res.get("questions", []) if q["subject"] == "mobile-core"), None)
    if q is None:
        pytest.skip("no mobile-core question available for the durability test")

    checkpointer = get_sqlite_checkpointer(engagement=ENGAGEMENT, base_dir=ARTIFACTS)
    graph = build_intake_graph(checkpointer=checkpointer)
    cfg = {"configurable": {"thread_id": q["id"]}}
    graph.invoke(
        {"question_id": q["id"],
         "answer_text": "The core is a dedicated 5G standalone core, national, "
                        "two sites active-active, with slicing reserved for the "
                        "mission-critical service.",
         "author": "Rui Vasconcelos", "role": "mobile-core-architect",
         "engagement": ENGAGEMENT, "db_path": str(DB_PATH)},
        config=cfg,
    )

    persisted = checkpointer.get(cfg)
    assert persisted is not None and "channel_values" in persisted, (
        "the state must be written to SQLite before the user is interrupted"
    )

    del graph, checkpointer  # the process that paused is gone

    proc_db = ARTIFACTS / "graph_proc"
    lbug_file = DB_PATH.with_suffix(".lbug")
    proc_lbug = proc_db.with_suffix(".lbug")

    if DB_PATH.exists():
        if proc_db.exists():
            shutil.rmtree(proc_db) if proc_db.is_dir() else proc_db.unlink()
        if DB_PATH.is_dir():
            shutil.copytree(DB_PATH, proc_db)
        else:
            shutil.copy(DB_PATH, proc_db)
    elif lbug_file.exists():
        if proc_lbug.exists():
            proc_lbug.unlink()
        shutil.copy(lbug_file, proc_lbug)
    else:
        proc_db.mkdir(parents=True, exist_ok=True)

    script = textwrap.dedent(f"""
        import gc
        from tools.elicitation.flows.intake import build_intake_graph, get_sqlite_checkpointer
        from langgraph.types import Command
        from mcp_server.db.kuzu_client import KuzuClient
        from tools.adapters.ladybug_store import LadybugGraphStore
        cp = get_sqlite_checkpointer(engagement="{ENGAGEMENT}", base_dir="{ARTIFACTS}")
        g = build_intake_graph(checkpointer=cp)
        r = g.invoke(Command(resume={{"action": "accept", "accept": True, "db_path": "{proc_db}"}}),
                     config={{"configurable": {{"thread_id": "{q['id']}"}}}})
        print(len(r.get("persisted_statement_ids", [])))
        LadybugGraphStore.clear_cache()
        KuzuClient.clear_cache()
        gc.collect()
    """)

    repo.close()
    if hasattr(repo, "db_client") and repo.db_client:
        repo.db_client = None
    from mcp_server.db.kuzu_client import KuzuClient
    KuzuClient.clear_cache(str(DB_PATH))
    Path(f"{DB_PATH}/.lock").unlink(missing_ok=True)

    proc = subprocess.run([sys.executable, "-c", script], capture_output=True, text=True)

    Path(f"{DB_PATH}/.lock").unlink(missing_ok=True)
    if DB_PATH.exists():
        shutil.rmtree(DB_PATH) if DB_PATH.is_dir() else DB_PATH.unlink()
    elif lbug_file.exists():
        lbug_file.unlink()

    if proc_db.exists():
        shutil.copytree(proc_db, DB_PATH) if proc_db.is_dir() else shutil.copy(proc_db, DB_PATH)
    elif proc_lbug.exists():
        shutil.copy(proc_lbug, lbug_file)

    repo.db_client = repo.graph_store

    assert proc.returncode in (0, -11), (
        f"resuming from a separate process failed — the durability model is "
        f"wrong and an expert cannot answer three days later:\n{proc.stderr[-800:]}"
    )
    assert int(proc.stdout.strip().splitlines()[-1]) >= 1

    report.note("""
        The conversation was paused in this process and resumed in a **separate
        one**, addressed only by the question identifier. This is what allows an
        expert to answer three days later; without it the model is a demo.
    """)
    completed(state, "act-2b")


