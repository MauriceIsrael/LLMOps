def test_act6_arbitration_amends_keeps_and_generates(repo, report, state):
    """Arbitration is not winner-takes-all."""
    requires(state, "act-5a")
    report.act("Act 6 — arbitration: amend one, keep the other, record the consequence")

    s34, s41 = state["s34"], state["s41"]
    amended = "floor arbitration terminates in the MC service layer at the site"
    reason = ("Both are right and the disagreement is one of scope. Arbitration is "
              "local; the end-to-end floor grant is not, because it depends on "
              "admission in the core.")

    repo.arbitrate_conflict(
        conflict_id=state["conflict_declared"], keep_statement_id=s41,
        reason=reason, arbitrated_by="Sofia Lindqvist",
        amend_statement_id=s34, amend_to=amended,
    )

    get_statement = api(repo, "get_statement", "the amended statement must be inspectable")
    a34 = get_statement(s34)
    assert a34["value"] == amended and a34["status"] == "active"
    assert a34.get("previous_values"), (
        "the previous wording must survive: an amendment is a change, not an erasure"
    )
    assert get_statement(s41)["status"] == "active"

    get_conflict = api(repo, "get_conflict", "arbitration must be traceable")
    conf = get_conflict(state["conflict_declared"])
    assert conf["status"] == "arbitrated"
    assert reason[:40] in conf["resolution"], "the rationale is the deliverable"
    assert conf.get("arbitrated_by") == "Sofia Lindqvist"

    report.note("""
        Sofia amended one statement and kept the other, because the disagreement
        was one of scope rather than of substance. The previous wording is in the
        history. An arbitration that could only pick a winner would have forced
        her to discard a true statement.
    """)
    report.table(["Statement", "Status", "Value"],
                 [[s34, a34["status"], a34["value"]],
                  [s41, "active", get_statement(s41)["value"]]])
    completed(state, "act-6")


