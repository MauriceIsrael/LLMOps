"""
Acceptance test for the Nordwave MCX scenario, and the generator of its
progression report.

Two things at once, on purpose:

  * it **verifies** the behaviour specified in tools/elicitation/SCENARIO-MCX.md,
    asserting the things that are hard rather than the things that are easy;
  * it **produces** the deliverables — a progression report with diagrams and
    boards, the assembled document, and an inspectable database.

Design rules, which are the point of the rewrite:

  1. No repository call may substitute for the behaviour under test. If an act
     is about extraction, the statements must come from the extraction. If it is
     about decomposition creating subjects, the subjects must come from the
     decomposition. Seeding is allowed only for material the act does not test.
  2. The report is generated from the graph, never written by hand. If the code
     does not do what the report claims, the report changes.
  3. One test function per act. A failure names the act, and the report is still
     written up to the point of failure.
  4. Both conflict paths are exercised: `contest_statement` declares, and
     `check_node` detects. Only the second proves detection works.
  5. Nothing is written to a temporary directory. The team must be able to open
     the artefacts afterwards.

Run:

    pytest tests/test_scenario_nordwave_mcx.py -v
    open artifacts/nordwave-mcx-2027/progression.md
"""

