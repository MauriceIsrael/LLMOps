def test_act7_assembly_is_provisional_for_a_maturity_reason(repo, report, state):
    """The discriminating test: provisional despite no open conflict."""
    requires(state, "act-6")
    report.act("Act 7 — assembly: provisional because subjects are immature")

    res = build_assemble_graph().invoke({"engagement": ENGAGEMENT, "db_path": str(DB_PATH)})

    assert res["is_provisional"] is True
    unripe = res.get("unripe_subjects", [])
    assert unripe, "a provisional document must name the subjects that are not ripe"

    open_conflicts = res.get("open_conflicts")
    assert open_conflicts is not None, (
        "assembly must report the number of open conflicts, otherwise a "
        "provisional status cannot be attributed to the right cause"
    )
    # The point of the whole act: arbitrating one conflict does not complete a document.
    assert res["is_provisional"] and open_conflicts <= 1, (
        "the document must remain provisional on maturity grounds even once "
        "conflicts are resolved"
    )

    sections = res.get("section_status", {})
    assert sections, "per-section status is required to know what is usable today"

    doc = ARTIFACTS / "document.md"
    doc.write_text(res.get("document", ""), encoding="utf-8")
    assert doc.stat().st_size > 0

    report.note(f"""
        Status **PROVISIONAL**, with **{open_conflicts}** conflict(s) open and
        **{len(unripe)}** subjects below `L3_decided`. The reason matters: the
        document is not held back by a disagreement but by immaturity. A run
        that reaches COMPLETE here has failed — this engagement is not finished.
    """)
    report.table(["Section", "Status"], [[k, v] for k, v in sorted(sections.items())])
    report.table(["Subject not ripe", "Level"],
                 [[u["subject"], u.get("level", "?")] for u in unripe])
    report.board(repo, "Maturity board at assembly")
    completed(state, "act-7")


